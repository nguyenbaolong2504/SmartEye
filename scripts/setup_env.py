"""Switch run mode while preserving API keys and backing up an existing .env."""
import argparse
from datetime import datetime
from pathlib import Path
import secrets
import shutil
from dotenv import dotenv_values

ROOT=Path(__file__).resolve().parents[1]


def configure(mode,root=ROOT):
    root=Path(root)
    target=root/'.env'
    values=dict(dotenv_values(root/'.env.example'))
    if target.is_file():
        values.update({k:v for k,v in dotenv_values(target).items() if v is not None})
        backup=root/f'.env.backup-{datetime.now().strftime("%Y%m%d-%H%M%S-%f")}'
        shutil.copyfile(target,backup)
    for name in ('DATABASE_URL','DB_ENGINE','POSTGRES_HOST','POSTGRES_PORT','POSTGRES_DB','POSTGRES_USER','POSTGRES_PASSWORD'):
        values.pop(name,None)
    values.update({'APP_ENV':'development','COOKIE_SECURE':'false','MONGODB_DB':values.get('MONGODB_DB') or 'smarteye'})
    if mode=='local':
        values.update({'MONGODB_URI':'mongodb://127.0.0.1:27017/','MONGODB_HOST':'127.0.0.1','MONGODB_PORT':'27017',
                       'APP_BASE_URL':'http://127.0.0.1:5173'})
        # URI selects unauthenticated local MongoDB; retain Docker credentials
        # so switching back cannot silently invalidate an existing Mongo volume.
    else:
        values.update({'MONGODB_URI':'','MONGODB_HOST':'127.0.0.1','MONGODB_PORT':values.get('MONGODB_DOCKER_PORT') or '27018',
                       'MONGODB_USERNAME':values.get('MONGODB_USERNAME') or 'smarteye_app',
                       'MONGODB_AUTH_SOURCE':values['MONGODB_DB'],
                       'MONGODB_PASSWORD':values.get('MONGODB_PASSWORD') or secrets.token_urlsafe(24),
                       'MONGO_ROOT_USERNAME':values.get('MONGO_ROOT_USERNAME') or 'smarteye_root',
                       'MONGO_ROOT_PASSWORD':values.get('MONGO_ROOT_PASSWORD') or secrets.token_urlsafe(32),
                       'APP_BASE_URL':f"http://localhost:{values.get('FRONTEND_PORT') or '8080'}" if mode=='docker' else 'http://127.0.0.1:5173'})
    def quote(value):
        return "'"+str(value or '').replace('\\','\\\\').replace("'","\\'")+"'"
    text='# Local configuration. Do not commit. Generated by scripts/setup_env.py.\n'
    text+='\n'.join(f'{key}={quote(value)}' for key,value in values.items())+'\n'
    temporary=root/'.env.pending'
    temporary.write_text(text,encoding='utf-8',newline='\n')
    temporary.replace(target)
    return target


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mode',choices=['local','db-docker','docker'],required=True)
    args=parser.parse_args()
    configure(args.mode)
    print(f'.env configured for {args.mode}; API keys preserved; existing .env backed up. Passwords were not printed.')
