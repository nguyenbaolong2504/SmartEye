"""Build distributable DB/SQL from synthetic fixtures, never from the working DB."""
import argparse
from contextlib import closing
import json
from pathlib import Path
import shutil
import sqlite3
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from sqlalchemy import create_engine, select
from sqlalchemy.dialects import postgresql, sqlite
from sqlalchemy.orm import Session
from sqlalchemy.schema import CreateIndex, CreateTable
from backend.app.db import Base
from backend.app import models
from backend.app.seed import seed_demo_roads
from backend.app.demo_accounts import seed_demo_accounts


def sql_literal(value):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return 'TRUE' if value else 'FALSE'
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (dict, list)):
        value = json.dumps(value, ensure_ascii=False)
    return "'" + str(value).replace("'", "''") + "'"


def build(output_directory):
    output_directory = Path(output_directory)
    output_directory.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='smarteye-clean-demo-') as directory:
        path = Path(directory) / 'demo.sqlite3'
        engine = create_engine(f'sqlite:///{path.as_posix()}')
        Base.metadata.create_all(engine)
        with Session(engine) as db:
            # These functions do not inspect ADMIN_EMAIL/ADMIN_PASSWORD or live records.
            seed_demo_roads(db)
            seed_demo_accounts(db)
            db.commit()
        tables = Base.metadata.sorted_tables
        records = {}
        with engine.connect() as conn:
            for table in tables:
                query = select(table).order_by(*table.primary_key.columns)
                records[table.name] = [dict(row._mapping) for row in conn.execute(query)]
        engine.dispose()
        with closing(sqlite3.connect(path)) as conn:
            assert conn.execute('PRAGMA integrity_check').fetchone()[0] == 'ok'
            assert not conn.execute('PRAGMA foreign_key_check').fetchall()
        shutil.copyfile(path, output_directory / 'smarteye-demo.sqlite3')

        for name, dialect in [('sqlite', sqlite.dialect()), ('postgresql', postgresql.dialect())]:
            header = '-- Generated by scripts/build_demo_database.py from SQLAlchemy models.\n'
            schema = [header, '-- Import into an empty database. Does not drop existing tables.\n']
            if name == 'sqlite':
                schema.append('PRAGMA foreign_keys=ON;\n')
            schema.append('BEGIN;\n')
            for table in tables:
                schema.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ';\n')
                for index in sorted(table.indexes, key=lambda i:i.name):
                    schema.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ';\n')
            schema.append('COMMIT;\n')
            (output_directory / f'schema.{name}.sql').write_text('\n'.join(schema), encoding='utf-8')

            seed = [header, '-- PUBLIC DEMO ACCOUNTS ONLY. Never import into a production database.\n', 'BEGIN;\n']
            for table in tables:
                columns = ', '.join(f'"{column.name}"' for column in table.columns)
                for row in records[table.name]:
                    values = ', '.join(sql_literal(row[column.name]) for column in table.columns)
                    seed.append(f'INSERT INTO "{table.name}" ({columns}) VALUES ({values});')
                if name == 'postgresql' and records[table.name] and 'id' in table.c and str(table.c.id.type) == 'INTEGER':
                    maximum = max(row['id'] for row in records[table.name])
                    seed.append(f"SELECT setval(pg_get_serial_sequence('{table.name}', 'id'), {maximum}, true);")
            seed.append('\nCOMMIT;\n')
            (output_directory / f'seed.demo.{name}.sql').write_text('\n'.join(seed), encoding='utf-8')
    return {table:len(rows) for table,rows in records.items()}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'database')
    args = parser.parse_args()
    counts = build(args.output)
    print('Built synthetic demo database:', json.dumps(counts, ensure_ascii=False))
